// 創建新 API 組合群組到圖像的映射
export function mapCombinedGroupToImageKey(productGroup) {
    const mapping = {
        "All": "ALL",
        "Keno": "KENO",
        "Live Dealer": "LIVEDEALER",
        "P2P/Instant Game/Fishing": "P2PFISHINSTANT", // 組合群組：P2P + Instant Games + Fishing
        "RNG/Slot": "SLOT",
        "Sportsbook/Esports": "SPORTESPORT", // 組合群組：Sportsbook + Esports


        // Numeric IDs (from betting record API)
        "1": "KENO",        // Keno
        "2": "LIVEDEALER",  // Live Dealer
        "3": "P2PFISHINSTANT",         // P2P / Instant Game / Fishing
        "4": "SLOT",        // RNG
        "5": "SPORTESPORT",   // Sportsbook/Esport/Cock Fight (M2M3)
        "7": "P2PFISHINSTANT"  // P2P / Instant Game / Fishing (also maps to same as 3)
    };
    return mapping[productGroup] || "ALL";
}

